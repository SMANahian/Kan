import Foundation

/// index.md and index.jsonl at the library root.
///
/// The library may be a folder that already had files of these names (an Obsidian vault's home
/// note): Kan rewrites a file only when it wrote it, like AGENTS.md. Its index.md starts with
/// `markdownMarker` (older versions: the "# Kan call library" heading); its index.jsonl is empty or
/// starts with a call summary.
enum LibraryIndexFiles {
    static let header = "| Date | Title | Folder | Tags | Duration | People | Status |\n|---|---|---|---|---|---|---|"
    static let markdownMarker = "<!-- kan-index: generated by Kan from the call records; edits are overwritten -->"
    private static let markdownMarkerPrefix = "<!-- kan-index"
    private static let legacyHeading = "# Kan call library\n"
    /// Bytes read to recognize a file (a summary line is well under this).
    static let recognitionBytes = 64 * 1024

    /// True if an existing index.md (its first bytes) was written by Kan.
    static func isKanMarkdown(_ head: Data) -> Bool {
        let text = String(decoding: head.prefix(512), as: UTF8.self)
        return text.hasPrefix(markdownMarkerPrefix) || text.hasPrefix(legacyHeading)
            || text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// True if an existing index.jsonl (its first bytes) was written by Kan: empty, or its first
    /// line is a compact call summary. Recognized by its keys (sorted, so they come early) rather
    /// than parsed, because a summary with a huge title may not fit in `head`.
    static func isKanJSONL(_ head: Data) -> Bool {
        let text = String(decoding: head, as: UTF8.self)
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return true }
        let firstLine = text.prefix { $0 != "\n" }
        guard firstLine.hasPrefix("{") else { return false }
        return ["\"id\":\"", "\"jsonPath\":\"", "\"markdownPath\":\""].allSatisfy { firstLine.contains($0) }
    }

    /// One index.md table row (entries are pre-rendered so regenerating the file is a join).
    static func row(summary: CallSummary, people: [String]) -> String {
        // A CommonMark <…> destination keeps the path readable (spaces and Bangla as they are).
        // Kan's own names never contain "<" or ">"; folders made outside Kan might.
        let target = summary.markdownPath.replacingOccurrences(of: "<", with: "%3C").replacingOccurrences(of: ">", with: "%3E")
        let link = "[\(escapeLinkText(cell(summary.title)))](<\(target)>)"
        let cells = [
            LibraryNaming.displayDate(summary.startedAt, timeZone: summary.timeZone),
            (summary.starred ? "★ " : "") + link,
            cell(summary.folder.isEmpty ? LibraryNaming.inboxDirectory : summary.folder),
            cell(summary.tags.joined(separator: ", ")),
            KanTime.humanDuration(summary.duration),
            cell(people.joined(separator: ", ")),
            summary.status.rawValue,
        ]
        return "| " + cells.joined(separator: " | ") + " |"
    }

    static func markdown(rows: [String]) -> String {
        var out = markdownMarker + "\n# Kan call library\n\n"
        out += "Every call Kan recorded, newest first. This file is regenerated automatically — don't edit it. "
        out += "Each call is a `.md` transcript with a sibling `.json` record; see [AGENTS.md](AGENTS.md) for the format.\n\n"
        if rows.isEmpty {
            out += "_No calls yet._\n"
            return out
        }
        out += "\(rows.count) call\(rows.count == 1 ? "" : "s").\n\n"
        out += header + "\n"
        out += rows.joined(separator: "\n") + "\n"
        return out
    }

    static func jsonl(lines: [String]) -> String {
        let kept = lines.filter { !$0.isEmpty }
        return kept.isEmpty ? "" : kept.joined(separator: "\n") + "\n"
    }

    /// Table-cell safe: single line, pipes escaped.
    static func cell(_ text: String) -> String {
        text.singleLine.replacingOccurrences(of: "|", with: "\\|")
    }

    private static func escapeLinkText(_ text: String) -> String {
        text.replacingOccurrences(of: "[", with: "\\[").replacingOccurrences(of: "]", with: "\\]")
    }
}
